import { readFile, rename, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { english } from '../hooks/voice-status-i18n.js'

const targets = {
  am: 'Amharic', bn: 'Bengali', bho: 'Bhojpuri', 'zh-Hans': 'Simplified Chinese',
  'zh-Hant': 'Traditional Chinese', da: 'Danish', nl: 'Dutch', fil: 'Filipino',
  fi: 'Finnish', 'fr-FR': 'French (France)', 'de-DE': 'German (Germany)',
  gu: 'Gujarati', ha: 'Hausa', 'hi-IN': 'Hindi (India)', 'id-ID': 'Indonesian',
  'it-IT': 'Italian', 'ja-JP': 'Japanese', kn: 'Kannada', 'ko-KR': 'Korean',
  ml: 'Malayalam', mr: 'Marathi', nb: 'Norwegian Bokmål', 'pt-BR': 'Portuguese (Brazil)',
  ru: 'Russian', 'es-419': 'Latin American Spanish', 'es-ES': 'Spanish (Spain)',
  sw: 'Swahili', sv: 'Swedish', ta: 'Tamil', te: 'Telugu', th: 'Thai',
  tr: 'Turkish', uk: 'Ukrainian', vi: 'Vietnamese',
}
const output = fileURLToPath(new URL('../hooks/voice-status-catalogs.js', import.meta.url))
const args = process.argv.slice(2)
const dryRun = args.includes('--dry-run')
const requested = args.filter(arg => arg !== '--dry-run')
const locales = requested.includes('--all') ? Object.keys(targets) : requested
if (!locales.length || locales.some(locale => !targets[locale])) {
  console.error('Usage: node scripts/generate-voice-status-translations.mjs --all|<locale>... [--dry-run]')
  process.exitCode = 2
} else {
  const source = await readFile(output, 'utf8')
  const old = source.match(/export default (\{[\s\S]*\})\s*$/)?.[1]
  const catalogs = old ? JSON.parse(old) : {}
  const pending = locale => Object.entries(english).filter(([key, text]) =>
    catalogs[locale]?.[key]?.source !== text || !catalogs[locale]?.[key]?.text)
  const count = locales.reduce((total, locale) => total + pending(locale).length, 0)
  console.log(`${locales.length} locales, ${count} strings need translation`)
  if (!dryRun && count) {
    let apiKey = process.env.GEMINI_API_KEY
    if (!apiKey) {
      try {
        const saved = JSON.parse(await readFile(join(homedir(), '.claude', 'voicemesh-controls', 'providers.json'), 'utf8'))
        apiKey = saved.gemini?.key
      } catch { /* A developer can supply GEMINI_API_KEY instead. */ }
    }
    if (!apiKey) { console.error('Gemini key unavailable; no files changed'); process.exitCode = 2 }
    else {
      let next = 0
      let save = Promise.resolve()
      const failed = []
      const worker = async () => {
        while (next < locales.length) {
          const locale = locales[next++]
          const entries = pending(locale)
          if (!entries.length) continue
          try {
            const response = await fetch('https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent', {
              method: 'POST',
              headers: { 'content-type': 'application/json; charset=utf-8', 'x-goog-api-key': apiKey },
              body: JSON.stringify({
                contents: [{ parts: [{ text: `Translate these VoiceMesh status and accessibility messages from English to ${targets[locale]}. Return only a JSON object with exactly the same keys. Preserve {placeholders} verbatim. Keep VoiceMesh, Claude, Composer, and API names unchanged. Make short status text concise. Distinguish regional and Chinese-script variants.\n${JSON.stringify(Object.fromEntries(entries))}` }] }],
                generationConfig: { responseMimeType: 'application/json', temperature: 0 },
              }),
            })
            if (!response.ok) throw new Error(`HTTP ${response.status}`)
            const body = await response.json()
            const translations = JSON.parse(body?.candidates?.[0]?.content?.parts?.map(part => part.text || '').join('') || '')
            if (!translations || Array.isArray(translations) || Object.keys(translations).length !== entries.length ||
                entries.some(([key]) => typeof translations[key] !== 'string' || !translations[key].trim())) throw new Error('Incomplete response')
            const catalog = { ...(catalogs[locale] ?? {}) }
            for (const [key, text] of entries) {
              const translated = translations[key].trim()
              const placeholders = value => [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort().join(',')
              if (placeholders(translated) !== placeholders(text)) throw new Error(`${key}: placeholders changed`)
              catalog[key] = { source: text, text: translated }
            }
            for (const key of Object.keys(catalog)) if (!(key in english)) delete catalog[key]
            save = save.then(async () => {
              catalogs[locale] = catalog
              const temp = `${output}.tmp`
              await writeFile(temp, `// Generated by scripts/generate-voice-status-translations.mjs. English is in voice-status-i18n.js.\nexport default ${JSON.stringify(catalogs, null, 2)}\n`)
              await rename(temp, output)
              console.log(`${locale}: ${entries.length} strings updated`)
            })
            await save
          } catch (error) { failed.push(locale); console.error(`${locale}: ${error.message}`) }
        }
      }
      await Promise.all(Array.from({ length: 3 }, worker))
      if (failed.length) { console.error(`${failed.length} locales failed; rerun to resume`); process.exitCode = 1 }
    }
  }
}
